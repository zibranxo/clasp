# ── command ──────────────────────────────────────────────────────────────────

def init_cmd() -> None:
    """Interactive first-time setup wizard. Creates ~/.clasp/config.yaml."""

    typer.echo("")
    typer.echo("  ◆ CLASP — First-time Setup Wizard")
    typer.echo("  ────────────────────────────────────")
    typer.echo("  Configure providers and API keys to get started.")
    typer.echo("  (Press Ctrl+C at any time to cancel)\n")

    # ── check for existing config ─────────────────────────────────────────────
    if CONFIG_PATH.exists():
        overwrite = typer.confirm(
            f"  Config already exists at {CONFIG_PATH}. Overwrite?",
            default=False,
        )
        if not overwrite:
            typer.echo("  Aborted — existing config kept.")
            raise typer.Exit(0)
        typer.echo("")

    # ── provider selection ────────────────────────────────────────────────────
    typer.echo("  Step 1 — Choose providers to enable")
    typer.echo("  (You can add more later via `clasp server` UI)\n")

    for i, prov in enumerate(PROVIDERS, start=1):
        default_enable = prov["name"] in ("nvidia_nim", "gemini", "cerebras", "groq")
        enable = typer.confirm(
            f"  [{i:2d}] {prov['label']}\n       {prov['note']}\n       Enable?",
            default=default_enable,
        )
        prov["_enabled"] = enable
        typer.echo("")

    enabled = [p for p in PROVIDERS if p.get("_enabled")]

    if not enabled:
        typer.echo("  ⚠ No providers selected. You can configure them later in the UI.")
        typer.echo("    Add at least one provider API key to start routing requests.\n")

    # ── API keys ──────────────────────────────────────────────────────────────
    typer.echo("  Step 2 — Enter API keys for enabled providers\n")

    for prov in enabled:
        name  = prov["name"]
        label = prov["label"]
        hint  = prov.get("key_hint")

        # Local providers don't need keys
        if hint is None:
            typer.echo(f"  {label}: no API key required (local model server)\n")
            prov["_keys"] = []
            continue

        keys: list[str] = []
        prompt_label = f"  {label} API key{' (blank to skip)' if not keys else ' (blank to finish)'}"

        while True:
            key = typer.prompt(prompt_label, default="", hide_input=True, show_default=False)
            key = key.strip()
            if not key:
                if not keys:
                    typer.echo(f"    ⚠ No key added for {label}. You can add one later in the UI.\n")
                break
            keys.append(key)
            typer.echo(f"    ✓ Key added ({key[:6]}{'*' * max(0, len(key)-10)}{key[-4:] if len(key) > 10 else ''})")
            if not prov["multi_key"]:
                typer.echo("")
                break
            typer.echo(f"    (Add another key for extra quota, or leave blank to continue)")

        prov["_keys"] = keys

    # ── server settings ───────────────────────────────────────────────────────
    typer.echo("  Step 3 — Server settings\n")

    port = typer.prompt("  Proxy port", default=8082, type=int)
    api_key = typer.prompt(
        "  Proxy API key (what Claude Code sends as Bearer token)",
        default="freecc",
    )
    typer.echo("")

    # ── write config ──────────────────────────────────────────────────────────
    cfg = _build_config(enabled, port, api_key)

    # Inject the real keys into the config dict
    for prov in PROVIDERS:
        name = prov["name"]
        keys = prov.get("_keys", [])
        if name in cfg["providers"] and "keys" in cfg["providers"][name]:
            cfg["providers"][name]["keys"] = keys

    CLASP_DIR.mkdir(parents=True, exist_ok=True)
    CONFIG_PATH.write_text(_write_yaml(cfg))

    typer.echo(f"  ✓ Config written to {CONFIG_PATH}")
    typer.echo(f"  ✓ {len(enabled)} provider(s) enabled: "
               f"{', '.join(p['label'] for p in enabled) or 'none'}\n")

    # ── launch server? ────────────────────────────────────────────────────────
    launch = typer.confirm("  Launch `clasp server` now?", default=True)
    if launch:
        typer.echo("")
        typer.echo("  Starting CLASP server...\n")
        try:
            # Replace current process with clasp server so the user sees live output
            import os, shutil
            clasp_bin = shutil.which("clasp") or sys.executable
            if shutil.which("clasp"):
                os.execvp("clasp", ["clasp", "server"])
            else:
                # Fall back to python -m clasp server
                os.execvp(sys.executable, [sys.executable, "-m", "clasp", "server"])
        except Exception as e:
            typer.echo(f"  ✗ Could not launch server: {e}", err=True)
            typer.echo("    Run it manually: clasp server")
            raise typer.Exit(1)
    else:
        typer.echo("  When you're ready, run:\n")
        typer.echo("    clasp server     # Start proxy + open config UI")
        typer.echo("    clasp claude     # Launch Claude Code through the proxy")
        typer.echo("")