# ── YAML writer (no ruamel dependency for the wizard) ────────────────────────

def _write_yaml(cfg: dict) -> str:
    """
    Minimal YAML serialiser sufficient for the config schema.
    Keys are written in a human-friendly order; string values are quoted.
    Falls back to ruamel.yaml if available for proper formatting.
    """
    try:
        from ruamel.yaml import YAML  # type: ignore[import]
        import io
        y = YAML()
        y.default_flow_style = False
        buf = io.StringIO()
        y.dump(cfg, buf)
        return buf.getvalue()
    except ImportError:
        pass

    # Pure-Python fallback — generates valid YAML for our schema
    lines: list[str] = [
        "# CLASP Configuration — generated by clasp init",
        "",
    ]

    def _emit(obj: object, indent: int = 0) -> None:
        pad = "  " * indent
        if isinstance(obj, dict):
            for k, v in obj.items():
                if isinstance(v, dict):
                    lines.append(f"{pad}{k}:")
                    _emit(v, indent + 1)
                elif isinstance(v, list):
                    lines.append(f"{pad}{k}:")
                    for item in v:
                        if isinstance(item, str):
                            lines.append(f'{pad}  - "{item}"')
                        else:
                            lines.append(f"{pad}  - {item}")
                elif isinstance(v, str):
                    lines.append(f'{pad}{k}: "{v}"')
                elif isinstance(v, bool):
                    lines.append(f'{pad}{k}: {"true" if v else "false"}')
                elif v is None:
                    lines.append(f"{pad}{k}: null")
                else:
                    lines.append(f"{pad}{k}: {v}")

    _emit(cfg)
    return "\n".join(lines) + "\n"


# ── config builder ────────────────────────────────────────────────────────────

def _build_config(
    enabled_providers: list[dict],
    port: int,
    api_key: str,
) -> dict:
    """Assemble the full config dict from wizard answers."""

    provider_chain = [p["name"] for p in enabled_providers]

    # Determine default model routing from enabled providers (first = primary)
    primary = provider_chain[0] if provider_chain else "nvidia_nim"

    # Smart defaults: prefer NIM for compute, Gemini for long context
    nim_enabled  = any(p["name"] == "nvidia_nim" for p in enabled_providers)
    gem_enabled  = any(p["name"] == "gemini"     for p in enabled_providers)
    cer_enabled  = any(p["name"] == "cerebras"   for p in enabled_providers)
    grq_enabled  = any(p["name"] == "groq"       for p in enabled_providers)

    def _default(candidates: list[str]) -> str:
        for c in candidates:
            if any(p["name"] == c for p in enabled_providers):
                return c
        return primary

    opus_prov    = _default(["nvidia_nim", "openrouter", "gemini"])
    sonnet_prov  = _default(["nvidia_nim", "gemini", "cerebras"])
    haiku_prov   = _default(["cerebras", "groq", "nvidia_nim"])
    fable_prov   = _default(["gemini", "nvidia_nim"])
    think_prov   = _default(["nvidia_nim", "gemini"])
    long_prov    = _default(["gemini", "openrouter", "nvidia_nim"])
    bg_prov      = _default(["groq", "cerebras", "nvidia_nim"])

    # All disabled providers still appear in the config (turned off)
    enabled_names = {p["name"] for p in enabled_providers}
    provider_section: dict = {}

